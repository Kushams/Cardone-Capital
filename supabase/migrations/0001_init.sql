-- 0001_init.sql — Cardone Capital investor portal, Postgres port of the
-- SQLite SCHEMA in src/lib/db.ts (CLONE-PROMPT §17 + §18 + §14 additions).
-- Conversions: INTEGER PKs -> bigint identity (BY DEFAULT so the seed can
-- insert explicit ids), 0/1 flags -> boolean, datetime('now') -> timestamptz
-- now(), JSON-in-TEXT -> jsonb. RLS is enabled on every table with no
-- policies (deny by default for anon/authenticated roles; the server uses
-- the service-role key). Storage buckets are private.

CREATE TABLE IF NOT EXISTS clients (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name text,
  email text NOT NULL UNIQUE,
  phone text,
  address text,
  date_of_birth_or_formation text,
  fincen_id text,
  dark_theme boolean NOT NULL DEFAULT false,
  onboarding_completed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS authorized_emails (
  email text PRIMARY KEY,
  invited_by text,
  status text NOT NULL DEFAULT 'INVITED' CHECK (status IN ('INVITED','ACTIVE','REVOKED')),
  invite_token_hash text,
  invite_expires_at timestamptz,
  token_purpose text,
  created_at timestamptz NOT NULL DEFAULT now(),
  activated_at timestamptz
);

CREATE TABLE IF NOT EXISTS outbox (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  to_email text NOT NULL,
  subject text NOT NULL,
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id bigint NOT NULL UNIQUE REFERENCES clients(id),
  email text NOT NULL UNIQUE REFERENCES authorized_emails(email),
  password_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash text PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS investing_entities (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id bigint NOT NULL REFERENCES clients(id),
  name text NOT NULL,
  entity_type text,
  is_disregarded boolean NOT NULL DEFAULT false,
  holding_title text,
  tax_address jsonb,
  tax_id_encrypted text,
  k1_name text,
  formation_date text,
  distribution_method jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS entity_contacts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id bigint NOT NULL REFERENCES investing_entities(id) ON DELETE CASCADE,
  name text NOT NULL,
  emails jsonb NOT NULL DEFAULT '[]'::jsonb,
  phones jsonb NOT NULL DEFAULT '[]'::jsonb,
  is_primary boolean NOT NULL DEFAULT false,
  document_access text NOT NULL DEFAULT 'All Documents',
  required_signer boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS bank_accounts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id bigint NOT NULL REFERENCES investing_entities(id) ON DELETE CASCADE,
  nickname text, bank_name text, account_type text,
  routing_encrypted text, account_encrypted text
);

CREATE TABLE IF NOT EXISTS offerings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  portal_id bigint NOT NULL,
  kind text NOT NULL CHECK (kind IN ('new','recent')),
  name text NOT NULL,
  slug text NOT NULL UNIQUE,
  sort_order bigint NOT NULL,
  data jsonb NOT NULL,
  UNIQUE (kind, portal_id)
);

CREATE TABLE IF NOT EXISTS commitments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  investing_entity_id bigint NOT NULL REFERENCES investing_entities(id),
  offering_id bigint NOT NULL REFERENCES offerings(id),
  desired_commitment bigint NOT NULL,
  contributed bigint,
  status text NOT NULL DEFAULT 'IN_PROGRESS'
);

CREATE TABLE IF NOT EXISTS document_templates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  offering_id bigint REFERENCES offerings(id),
  doc_type text NOT NULL CHECK (doc_type IN ('PPM','OPERATING_AGREEMENT','SUBSCRIPTION_BOOKLET','W9','WIRE_INSTRUCTIONS','MEMORANDUM')),
  display_name text NOT NULL,
  master_file_path text NOT NULL,
  version text NOT NULL DEFAULT '1',
  is_personalised boolean NOT NULL DEFAULT false,
  field_map jsonb,
  year bigint,
  shared_date text NOT NULL,
  doc_type_label text NOT NULL DEFAULT 'Agreements',
  appears_in jsonb NOT NULL DEFAULT '[]'::jsonb
);

CREATE TABLE IF NOT EXISTS document_instances (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id bigint NOT NULL REFERENCES document_templates(id),
  client_id bigint NOT NULL REFERENCES clients(id),
  investing_entity_id bigint NOT NULL REFERENCES investing_entities(id),
  commitment_id bigint REFERENCES commitments(id),
  generated_file_path text,
  executed_file_path text,
  status text NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PENDING_SIGNATURE','SIGNED','EXECUTED')),
  requested_at timestamptz,
  signed_at timestamptz
);

CREATE TABLE IF NOT EXISTS signature_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_instance_id bigint NOT NULL REFERENCES document_instances(id),
  investing_entity_id bigint NOT NULL REFERENCES investing_entities(id),
  requested_at timestamptz NOT NULL,
  status text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','AGREED','SIGNED')),
  signature_page_id bigint NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS tax_forms (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id bigint NOT NULL REFERENCES clients(id),
  investing_entity_id bigint REFERENCES investing_entities(id),
  name text NOT NULL, investment text, tax_year bigint,
  shared_date text NOT NULL, file_path text
);

CREATE TABLE IF NOT EXISTS transactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id bigint NOT NULL REFERENCES clients(id),
  investing_entity_id bigint REFERENCES investing_entities(id),
  tx_date text NOT NULL, kind text NOT NULL, description text,
  investment text, amount_cents bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_entities_client ON investing_entities(client_id);
CREATE INDEX IF NOT EXISTS idx_instances_client ON document_instances(client_id, status);
CREATE INDEX IF NOT EXISTS idx_sigreq_entity ON signature_requests(investing_entity_id, status);

