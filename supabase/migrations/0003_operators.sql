-- 0003_operators.sql
-- Operator (staff) accounts for /operator. Until now the console was gated by a
-- single shared passphrase; this adds named accounts with roles. The founding
-- account is invest@cardonecapitalportal.us with role SUPERADMIN (user decision
-- 2026-11-02); further staff accounts are added later at the user's direction.
-- The legacy passphrase remains as a break-glass fallback in app code.
-- RLS: enabled, deny-by-default; only service_role is granted (same model as 0002).

CREATE TABLE public.operators (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  password_hash text,
  role text NOT NULL DEFAULT 'STAFF' CHECK (role IN ('SUPERADMIN', 'STAFF')),
  invite_token_hash text,
  invite_expires_at timestamptz,
  token_purpose text,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_login_at timestamptz
);

CREATE TABLE public.operator_sessions (
  token_hash text PRIMARY KEY,
  operator_id bigint NOT NULL REFERENCES public.operators (id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.operators ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.operator_sessions ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.operators TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.operator_sessions TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.operators_id_seq TO service_role;
