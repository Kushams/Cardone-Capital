-- 0006: client document uploads (audit item 4) + the private `uploads` bucket.
create table if not exists client_uploads (
  id bigint generated by default as identity primary key,
  client_id bigint not null references clients(id),
  original_name text not null,
  file_path text not null,
  content_type text not null,
  size_bytes bigint not null,
  uploaded_at timestamptz not null default now()
);
alter table client_uploads enable row level security;
grant select, insert, update, delete on client_uploads to service_role;
grant usage, select on sequence client_uploads_id_seq to service_role;
create index if not exists client_uploads_client_idx on client_uploads (client_id, uploaded_at desc);
insert into storage.buckets (id, name, public) values ('uploads', 'uploads', false)
on conflict (id) do nothing;
